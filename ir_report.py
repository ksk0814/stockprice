# CSV,Excelの操作に必要なライブラリをインポート
import csv
import openpyxl as px
from openpyxl import Workbook
from openpyxl.styles import Color, PatternFill, Font
from openpyxl.formula.translate import Translator
from openpyxl.worksheet.table import Table, TableStyleInfo
from openpyxl.chart import BarChart, Series, Reference

# 指定のフォルダにCSV形式のIRデータ(P/L)を置く（./はカレントディレクトリ(相対参照)）
csv_path = './fy-profit-and-loss.csv'
# WorkbookとWorksheetの変数を定義
wb = px.Workbook()
ws = wb.active

# CSVデータをExcelファイルへ1行ずつ読み込む
# 売上高、営業利益、純利益、EPSの数値が文字列で読み込まれてしまうため後で数値に変換する
with open(csv_path) as f:
    reader = csv.reader(f, delimiter=',')
    for row in reader:
        ws.append(row)

# 新たに指標を作る列を挿入
ws.insert_cols(4)
ws.insert_cols(5)
ws.insert_cols(6)
ws.insert_cols(10)

# 列名（新たに作る指標名）を代入
ws['D4'] = '増収率'
ws['E4'] = '増益率'
ws['F4'] = '成長性判定'
ws['J4'] = '株価'
ws['A21'] = '直近3期平均'

# 10/4追記：データの取得範囲を再度確認、個別のデータの行数に依存しないよう修正
# 売上高、営業利益の列を文字列から数値（整数型）へ変換（もし営業利益の列に"-"が入っていたらコメントアウトでOK）
for row in ws['B10:C19']:
    for cell in row:
        cell.value = int(cell.value)

# 同様に純利益の列を数値（整数型）へ変換
for row in ws['H5:H20']:
    for cell in row:
        cell.value = int(cell.value)

# 同様にEPSの列を数値（浮動小数点数型）へ変換
for row in ws['I7:I20']:
    for cell in row:
        cell.value = float(cell.value)

# 新たに指標を作るための数式を代入（指標名は列名を参照）
ws['D6'] = f'=IFERROR(B6/B5,"")'
ws['E6'] = f'=IFERROR(C6/C5,"")'
ws['F6'] = f'=IFERROR(D6+E5,"")'
# 以下、削除予定（直近３カ年は企業のデータによって行数が異なるため、行番号を指定しない）
# ws['D21'] = f'=IFERROR(AVERAGE(D17:D19),"")'
# ws['E21'] = f'=IFERROR(AVERAGE(E17:E19),"")'
# ws['F21'] = f'=IFERROR(D21+E21,"")'

# 直近から過去10年間のEPSの年間平均成長率を求める
# 末尾の行(max_row)から+10行上のI列の値とmax_rowのI列の値を取得し、(I(max_row)/I(max_row+10))^1/10-1を求める

# 相対参照で数式を縦方向へコピぺ
for col_no in range(4, 7):
    col_alphabet = ws.cell(row=1, column=col_no).column_letter
    for row_no in range(7, ws.max_row):
        cell_no = f'{col_alphabet}{row_no}'
        ws[cell_no] = Translator(ws[f'{col_alphabet}6'].value,
                                 origin=f'{col_alphabet}6').translate_formula(cell_no)

# 表示単位を%へ変更
for row in ws['D6:F21']:
    for cell in row:
	    cell.number_format= '0.00%'

# テーブルとして書式設定（見た目を整える）
table = Table(displayName='Table1', ref='A4:L20')
table_style = TableStyleInfo(name='TableStyleMedium2', showRowStripes=True)
table.tableStyleInfo = table_style
ws.add_table(table)

# 以下修正中のためコメントアウトにより無効化（投資判断の情報は別途作成予定）
# セルD21(直近3期平均の増収率)、E20(直近の増益率)を黄色で塗りつぶし、太字に(投資判断に使う情報を強調)
# 黄色で塗りつぶし
# fill = PatternFill(patternType="solid", fgColor="FFFF00")
