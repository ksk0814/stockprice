# 挿入するグラフの情報を定義
chart1 = BarChart()
# 縦棒型を指定
chart1.type = 'col'
# グラフの配色等を指定
chart1.style = 10
chart1.title = '売上高と営業利益の推移'
chart1.y_axis.title = '円'
chart1.x_axis.title = '年度'

# y軸の範囲を指定
data = Reference(ws, min_col=2, max_col=3, min_row=4, max_row=19)
# x軸の範囲を指定
cats = Reference(ws, min_col=1, min_row=5, max_row=19)
# 指定した範囲の参照データを渡す
chart1.add_data(data, titles_from_data=True)
chart1.set_categories(cats)
# バーの形状を指定
chart1.shape = 5
# グラフの挿入位置を指定
ws.add_chart(chart1, 'B23')

# 名前を付けてファイルを保存し、完了メッセージを出力
global file_name
code = ws['A3'] .value
file_name = f'IR_report_{code}.xlsx'
wb.save(file_name)
print(f'{code}のIRレポートを作成しました。')

# 株価（3/31又は直近の取得可能な日(ここでは3/29)）の値を代入
# レポートと転記する期末株価のファイルをそれぞれ読み込む
wb = px.load_workbook(file_name)
ws = wb.active
# 別のプログラム（stock_price.ipynb）を実行して期末株価のデータ'Close.xlsx'を事前に取得しておく
wb_copy = px.load_workbook('Close.xlsx')
ws_copy = wb_copy.active

for i in range(2,15):
    #コピー元の列を読み取り
    copy = ws_copy.cell(row = i, column = 6).value
    #Valueに指定した値を指定先の列に書き込む
    ws.cell(row = i + 5, column = 10, value = copy)
    i += 1

wb.save(file_name)
print(f'{file_name}への期末株価の転記が完了しました。')

